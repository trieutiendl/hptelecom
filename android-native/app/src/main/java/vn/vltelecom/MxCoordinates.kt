package vn.vltelecom

import org.json.JSONObject
import java.util.Locale

data class MxCoordinates(val lat:Double,val lon:Double,val source:String) {
    fun description()=IncidentRules.mxDescription("",lat,lon)
    /** Remove only a complete generated GPS line matching this photo; keep the user's other text. */
    fun captionWithoutCoordinates(caption:String):String {
        val formats=listOf(
            Regex("Tọa độ MX:\\s*([+-]?\\d+(?:\\.\\d+)?)\\s*,\\s*([+-]?\\d+(?:\\.\\d+)?)",RegexOption.IGNORE_CASE),
            Regex("Lat:\\s*([+-]?\\d+(?:\\.\\d+)?)\\s*\\|\\s*Long:\\s*([+-]?\\d+(?:\\.\\d+)?)",RegexOption.IGNORE_CASE)
        )
        fun rounded(value:Double)=String.format(Locale.US,"%.6f",value)
        var removed=false
        val kept=caption.lines().filter { line ->
            val match=formats.firstNotNullOfOrNull{it.matchEntire(line.trim())}
            val same=match!=null&&rounded(match.groupValues[1].toDouble())==rounded(lat)&&rounded(match.groupValues[2].toDouble())==rounded(lon)
            if(same)removed=true
            !same
        }
        return if(removed)kept.joinToString("\n").trim()else caption
    }
    fun metadata(previous:String=""):String {
        val value=runCatching{JSONObject(previous)}.getOrDefault(JSONObject())
        return value.put("lat",lat).put("lon",lon).put("gpsSource",source).toString()
    }
    companion object {
        fun of(lat:Double,lon:Double,source:String):MxCoordinates? =
            if(lat.isFinite()&&lon.isFinite()&&lat in -90.0..90.0&&lon in -180.0..180.0) MxCoordinates(lat,lon,source) else null
        fun fromMetadata(value:String):MxCoordinates?=runCatching{
            val json=JSONObject(value)
            fun point(source:JSONObject):MxCoordinates? = of(
                source.optDouble("lat",Double.NaN),source.optDouble("lon",Double.NaN),
                source.optString("gpsSource").ifBlank{source.optString("source").ifBlank{"Ảnh"}}
            )
            point(json)?:json.optJSONObject("gps")?.let(::point)
        }.getOrNull()
        /** The old Android auto-fill marker identifies generated captions. Unmarked legacy notes stay intact. */
        fun cleanAutomaticCaption(image:IncidentImage):IncidentImage {
            val json=runCatching{JSONObject(image.metadata)}.getOrNull()?:return image
            if(!json.optBoolean("mxCoordinateDescriptionApplied",false)||json.optBoolean("mxLegacyCaptionPreserved",false)||json.optBoolean("mxCoordinateCaptionReviewed",false))return image
            val point=fromMetadata(image.metadata)?:return image
            val caption=point.captionWithoutCoordinates(image.caption)
            return image.copy(caption=caption,metadata=json.put("mxCoordinateCaptionReviewed",true).toString())
        }
        /** A saved marker belongs to the photo, so later callbacks cannot undo a user's edits. */
        fun applyOnceToImage(group:IncidentGroup,index:Int,coordinates:MxCoordinates):Boolean {
            val image=group.images.getOrNull(index)?:return false
            val metadata=runCatching{JSONObject(image.metadata)}.getOrDefault(JSONObject())
            if(metadata.optBoolean("mxCoordinateDescriptionApplied",false))return false
            val row=index/2
            while(group.pairNotes.size<=row)group.pairNotes.add(group.note)
            group.pairNotes[row]=IncidentRules.mxDescription(group.pairNotes[row],coordinates.lat,coordinates.lon)
            group.images[index]=image.copy(metadata=JSONObject(coordinates.metadata(image.metadata)).apply{
                put("mxCoordinateDescriptionApplied",true)
                // An older photo's caption may have been entered by the user, not generated by OCR.
                if(image.caption.isNotBlank())put("mxLegacyCaptionPreserved",true)
            }.toString())
            return true
        }
        fun applyToImage(group:IncidentGroup,index:Int,coordinates:MxCoordinates) {
            val old=group.images[index]
            val previous=fromMetadata(old.metadata)
            group.images[index]=old.copy(metadata=coordinates.metadata(old.metadata))
            val row=index/2
            while(group.pairNotes.size<=row)group.pairNotes.add(group.note)
            val siblingUsesOld=previous!=null&&group.images.withIndex().any{(i,image)->
                i!=index&&i/2==row&&fromMetadata(image.metadata)?.description()==previous.description()
            }
            val lines=group.pairNotes[row].lines().map{it.trim()}.filter{it.isNotBlank()}
                .filter{previous==null||siblingUsesOld||it!=previous.description()}
            group.pairNotes[row]=(lines+coordinates.description()).distinct().joinToString("\n")
        }
    }
}
